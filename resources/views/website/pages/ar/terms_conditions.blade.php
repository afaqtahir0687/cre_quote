<p>يرجى قراءة هذه الشروط والأحكام بعناية قبل إنشاء حسابك أو استخدام منصة كري لوجيكس لإدارة الموارد (CreLogics ERP).</p>

<h3>1. الموافقة على الشروط</h3>
<p>من خلال إنشاء حساب، أو التسجيل في فترة التجربة المجانية، أو الوصول إلى النظام السحابي، فإنك توافق على الالتزام الكامل بهذه الشروط والأحكام وبكافة القوانين واللوائح المعمول بها تجارياً.</p>

<h3>2. تراخيص الاستخدام ونطاق الخدمة</h3>
<p>تمنحك كري لوجيكس ترخيصاً سحابياً غير حصري وقابل للإلغاء للوصول إلى النظام وفقاً لباقة اشتراكك وعدد الفروع المعتمدة لمنشأتك. يظل البرنامج وكافة الملكيات الفكرية والعلامات التجارية ملكاً حصرياً لشركة كري لوجيكس.</p>

<h3>3. مسؤولية الحساب وأمان الدخول</h3>
<p>تتحمل المسؤولية الكاملة عن الحفاظ على سرية بيانات تسجيل الدخول وكلمات المرور الخاصة بإدارة متجرك وموظفيك. وتتعهد بإشعارنا فوراً بأي استخدام غير مصرح به. ولا تتحمل كري لوجيكس أي مسؤولية عن أخطاء ناتجة عن إفشاء كلمات المرور محلياً.</p>

<h3>4. الاستخدام المقبول للمنصة</h3>
<p>تم تصميم منصة كري لوجيكس للإدارة التشغيلية والتجارية المشروعة. وتتعهد بعدم:</p>
<ul>
    <li>محاولة الهندسة العكسية، أو فك التشفير، أو استخراج الشيفرة المصدرية للتطبيق السحابي.</li>
    <li>إرسال ملفات ضارة، أو فيروسات، أو تنفيذ هجمات حرمان من الخدمة (DDoS) ضد البنية التحتية.</li>
    <li>استخدام النظام في إصدار فواتير احتيالية أو معاملات غير قانونية.</li>
</ul>

<h3>5. توفر الخدمة ومستوى الأداء (SLA)</h3>
<p>نحن نستهدف جاهزية وتوافر للنظام بنسبة 99.9%. وتتم أعمال الصيانة الدورية وتحديثات الخوادم في أوقات غير الذروة مع إرسال إشعارات مسبقة عبر لوحة التحكم كلما أمكن ذلك.</p>

<h3>6. إنهاء الخدمة وإلغاء الاشتراك</h3>
<p>يحق لك إنهاء أو إلغاء اشتراكك في أي وقت. كما تحتفظ كري لوجيكس بحق تعليق أو إنهاء الحسابات التي تنتهك سلامة النظام، أو تشارك في أنشطة احتيالية، أو تتخلف عن سداد رسوم التجديد بعد التنبيه المتكرر.</p>
