    <li><strong>السجلات التشغيلية والمالية:</strong> دليل العملاء، بنود عروض الأسعار، مواصفات أوامر التشغيل، سندات التسليم، وفواتير الضرائب المدخلة في قاعدة بيانات منشأتك.</li>
    <li><strong>سجلات النظام والمصادقة:</strong> عنوان بروتوكول الإنترنت (IP)، نوع المتصفح، أوقات تسجيل الدخول، وسجلات صلاحيات الموظفين لضمان أعلى مستويات الأمان.</li>
</ul>

<h3>2. العزل الصارم لبيانات المستأجرين</h3>
<p>يعتمد نظام كري لوجيكس على بنية سحابية متعددة المستأجرين متطورة مع عزل رقمي تام للبيانات. قوائم عملائك، وأسعار الوحدات، وتكاليف الموردين، وسجلات التشغيل مشفرة ومحصورة حصرياً برقم منشأتك المعتمد. لا يمكن لأي منشأة أخرى أو مستخدم غير مصرح له الاطلاع على بياناتك بأي شكل من الأشكال.</p>

