<h3>1. المعلومات التي نجمعها</h3>
<p>عندما تقوم بالتسجيل في حساب كري لوجيكس، أو الاستفادة من التجربة المجانية لمدة 7 أيام، أو تشغيل وحدات الفروع المتعددة، نقوم بجمع الفئات التالية من المعلومات:</p>
<ul>
